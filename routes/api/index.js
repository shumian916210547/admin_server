router.post(
  "/auth/login",
  loginLimiter,
  /**
   * 验证账号密码并建立浏览器会话，同时异步记录用户自己的登录活动。
   * @param {import("express").Request} req 含 username、password 的登录请求；不信任任何客户端租户字段。
   * @param {import("express").Response} res 写入 HttpOnly Cookie 和脱敏认证上下文的响应对象。
   * @returns {Promise<void>} 验证成功时返回认证上下文；失败时由统一错误中间件返回 400、401 或 429。
   */
  asyncHandler(async (req, res) => {
    const { username, password } = req.body || {};
    if (typeof username !== "string" || !username.trim() || typeof password !== "string" || !password) {
      throw badRequest("username and password are required");
    }

    try {
      const user = new Parse.User();
      user.set("username", username.trim());
      user.set("password", password);
      await user.logIn({ useMasterKey: true });
      const auth = await getAuthContext(user.id);
      const { token, csrfToken, sessionId } = createSession(auth.userId);
      setSessionCookie(res, token);
      try {
        await recordLoginActivity(auth, sessionId);
      } catch (activityError) {
        // 登录主流程不能因辅助统计暂时不可用而被拒绝；错误仍进入结构化日志以供运维追踪。
        logger.warn("dashboard.login_activity_unavailable", {
          requestId: req.requestId,
          userId: auth.userId,
          error: activityError.message,
        });
      }
      try {
        await registerAdminSession(auth, { sessionId }, req);
      } catch (sessionError) {
        // 会话登记是在线成员页的辅助能力，不能让已验证的登录因旧部署 Schema 尚未迁移而失败。
        logger.warn("admin_session.registration_unavailable", {
          requestId: req.requestId,
          userId: auth.userId,
          error: sessionError.message,
        });
      }
      res.json({ data: authPayload(auth, csrfToken), requestId: req.requestId });
    } catch (error) {
      if (error.status) throw error;
      throw unauthorized("Invalid username or password");
    }
  })
);

