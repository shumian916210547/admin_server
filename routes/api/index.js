function authPayload(auth, csrfToken) {
  return {
    user: serialize(auth.user, "_User"),
    company: serialize(auth.company, "Company"),
    role: auth.role ? serialize(auth.role, "Role") : null,
    isAdmin: auth.isAdmin,
    csrfToken,
  };
}

