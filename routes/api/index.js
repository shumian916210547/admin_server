router.post(
  "/files",
  csrfGuard,
  upload.single("file"),
  asyncHandler(async (req, res) => {
    if (!req.file) throw badRequest("A file is required");
    try {
      const uploadType = uploadTypeForMime(req.file.mimetype);
      if (!uploadType) throw badRequest("This file type is not allowed");
      const now = new Date();
      const dateParts = [
        String(now.getUTCFullYear()),
        String(now.getUTCMonth() + 1).padStart(2, "0"),
        String(now.getUTCDate()).padStart(2, "0"),
      ];
      const fileName = `${crypto.randomUUID()}${uploadType.extension}`;
      const relativePath = path.join(req.auth.userId, ...dateParts, fileName);
      const destination = path.resolve(config.upload.storageDir, relativePath);
      const storageRoot = `${path.resolve(config.upload.storageDir)}${path.sep}`;
      if (!destination.startsWith(storageRoot)) throw forbidden("Invalid file path");
      await fs.promises.mkdir(path.dirname(destination), { recursive: true });
      await fs.promises.rename(req.file.path, destination);
      res.status(201).json({
        data: {
          url: `/api/files/${req.auth.userId}/${dateParts.join("/")}/${fileName}`,
          name: req.file.originalname,
          size: req.file.size,
          mimetype: req.file.mimetype,
        },
        requestId: req.requestId,
      });
    } finally {
      // rename() removes the temporary file on success; this also cleans up
      // failed writes so a malicious or flaky upload cannot fill .tmp.
      await fs.promises.unlink(req.file.path).catch(() => {});
    }
  })
);

router.get(
  "/files/:userId/:year/:month/:day/:fileName",
  asyncHandler(async (req, res) => {
    const { userId, year, month, day, fileName } = req.params;
    if (!/^[A-Za-z0-9_-]+$/.test(userId) || !/^\d{4}$/.test(year) || !/^\d{2}$/.test(month) || !/^\d{2}$/.test(day) || !/^[a-f0-9-]+(?:\.[a-z0-9]+)?$/i.test(fileName)) {
      throw badRequest("Invalid file path");
    }
    await assertUserInTenant(req.auth, userId);
    const storageRoot = path.resolve(config.upload.storageDir);
    const filePath = path.resolve(storageRoot, userId, year, month, day, fileName);
    if (!filePath.startsWith(`${storageRoot}${path.sep}`)) throw forbidden("Invalid file path");
    if (!fs.existsSync(filePath)) throw notFound("File not found");
    const uploadType = uploadTypeByExtension.get(path.extname(fileName).toLowerCase());
    if (!uploadType) throw notFound("File not found");
    res.set({
      "Cache-Control": "private, no-store",
      "Content-Security-Policy": "sandbox; default-src 'none'; base-uri 'none'; form-action 'none'",
      "Cross-Origin-Resource-Policy": "same-origin",
      "X-Content-Type-Options": "nosniff",
    });
    if (!uploadType.inline) res.attachment(fileName);
    res.type(uploadType.mimeType);
    res.sendFile(filePath);
  })
);

